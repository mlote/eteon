/* =========================================================================
   MicFi - tools/generate-meta.js
   Writes the title, meta description, social share tags and structured data
   (schema.org) of every static page, using js/config.js as the single source.

   Why this exists: the same copy was written by hand into separate files, so
   the snippet people saw in Google could drift away from what the page
   actually said. Now there is one place to edit it.

   Blog posts are not handled here. Their title and description come from the
   post itself, in js/blog.js, written by tools/generate-posts.js.

   Run it after changing a title, description, brand value or FAQ in config.js:
       node tools/generate-meta.js
   No need to edit this file.
   ========================================================================= */
"use strict";

var fs = require("fs");
var path = require("path");
var vm = require("vm");

var ROOT = path.resolve(__dirname, "..");
var SITE = "https://micfi.net";
var START_LINE = "<!-- META:START";
var END_LINE = "<!-- META:END -->";
var SEO_START_LINE = "<!-- SEO:JSONLD START";
var SEO_END_LINE = "<!-- SEO:JSONLD END -->";

function loadConfig() {
  var sandbox = {};
  sandbox.window = sandbox;
  sandbox.MicFi = {};
  vm.createContext(sandbox);

  var code = fs.readFileSync(path.join(ROOT, "js/config.js"), "utf8");
  vm.runInContext(code, sandbox, { filename: "js/config.js" });

  return sandbox.MicFi;
}

function esc(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function jsonEsc(value) {
  return String(value)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/&/g, "\\u0026")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

function imageDims(relPath) {
  var file = path.join(ROOT, relPath.replace(/^\//, ""));
  if (!fs.existsSync(file)) return null;
  var b = fs.readFileSync(file);
  if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4E && b[3] === 0x47) {
    return { type: "image/png", w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
  }
  return null;
}

function buildMeta(urlPath, page) {
  var url = SITE + urlPath;
  var rel = page.ogImage || "/assets/blog/default.png";
  var image = SITE + rel;
  var dims = imageDims(rel);
  /* ogTitle is the shorter headline written on the link preview card.
     Fall back to the page title when it is not set. */
  var shareTitle = page.ogTitle || page.title;

  var lines = [
    START_LINE + " generated by tools/generate-meta.js from js/config.js. Do not edit by hand. -->",
    "  <title>" + esc(page.title) + "</title>",
    '  <meta name="description" content="' + esc(page.description) + '">',
    '  <link rel="canonical" href="' + esc(url) + '">',
    '  <meta property="og:type" content="website">',
    '  <meta property="og:site_name" content="MicFi">',
    '  <meta property="og:title" content="' + esc(shareTitle) + '">',
    '  <meta property="og:description" content="' + esc(page.ogDescription || page.description) + '">',
    '  <meta property="og:url" content="' + esc(url) + '">',
    '  <meta property="og:image" content="' + esc(image) + '">'
  ];

  if (dims) {
    lines.push('  <meta property="og:image:type" content="' + dims.type + '">');
    lines.push('  <meta property="og:image:width" content="' + dims.w + '">');
    lines.push('  <meta property="og:image:height" content="' + dims.h + '">');
  }

  lines.push(
    '  <meta property="og:image:alt" content="' + esc(shareTitle) + '">',
    '  <meta property="og:locale" content="en_US">',
    '  <meta name="twitter:card" content="summary_large_image">',
    '  <meta name="twitter:title" content="' + esc(shareTitle) + '">',
    '  <meta name="twitter:description" content="' + esc(page.ogDescription || page.description) + '">',
    '  <meta name="twitter:image" content="' + esc(image) + '">',
    '  <meta name="twitter:image:alt" content="' + esc(shareTitle) + '">',
    "  " + END_LINE
  );

  return lines.join("\n");
}

function buildSchema(M, urlPath) {
  var name = M.BRAND_NAME || "MicFi";
  var sameAs = [];
  var social = M.SOCIAL_LINKS || {};

  Object.keys(social).forEach(function (key) {
    if (social[key] && social[key] !== "#") sameAs.push(social[key]);
  });

  var organization = {
    "@context": "https://schema.org",
    "@type": "Organization",
    name: name,
    alternateName: M.BRAND_ALTERNATE || [],
    url: SITE + "/",
    logo: SITE + "/assets/mark.png",
    description: M.BRAND_DESCRIPTION || "",
    email: M.CONTACT_EMAIL,
    telephone: M.PHONE_NUMBER,
    address: {
      "@type": "PostalAddress",
      addressLocality: M.ADDRESS || "Kampala",
      addressCountry: "UG"
    },
    areaServed: {
      "@type": "Country",
      name: "Uganda"
    }
  };

  if (sameAs.length) organization.sameAs = sameAs;

  var website = {
    "@context": "https://schema.org",
    "@type": "WebSite",
    name: name,
    url: SITE + "/",
    publisher: {
      "@type": "Organization",
      name: name,
      url: SITE + "/"
    }
  };

  if (M.BRAND_ALTERNATE && M.BRAND_ALTERNATE.length) {
    website.alternateName = M.BRAND_ALTERNATE[0];
  }

  var items = [organization, website];

  if (urlPath === "/blog/") {
    items.push({
      "@context": "https://schema.org",
      "@type": "Blog",
      name: name + " Blog",
      url: SITE + "/blog/",
      publisher: {
        "@type": "Organization",
        name: name,
        url: SITE + "/"
      }
    });
  }

  if (urlPath === "/contact/") {
    var business = {
      "@context": "https://schema.org",
      "@type": "LocalBusiness",
      name: name,
      url: SITE + "/",
      image: SITE + "/assets/mark.png",
      email: M.CONTACT_EMAIL,
      telephone: M.PHONE_NUMBER,
      address: {
        "@type": "PostalAddress",
        addressLocality: M.ADDRESS || "Kampala",
        addressCountry: "UG"
      },
      areaServed: {
        "@type": "Country",
        name: "Uganda"
      }
    };
    if (sameAs.length) business.sameAs = sameAs;
    items.push(business);
  }

  if (urlPath === "/about/" && M.FAQ && M.FAQ.length) {
    items.push({
      "@context": "https://schema.org",
      "@type": "FAQPage",
      mainEntity: M.FAQ.map(function (item) {
        return {
          "@type": "Question",
          name: item.q,
          acceptedAnswer: {
            "@type": "Answer",
            text: item.a
          }
        };
      })
    });
  }

  return items;
}

function buildSchemaBlock(M, urlPath) {
  var lines = [
    SEO_START_LINE + " generated by tools/generate-meta.js from js/config.js. Do not edit by hand. -->"
  ];

  buildSchema(M, urlPath).forEach(function (item) {
    lines.push('  <script type="application/ld+json">' + jsonEsc(JSON.stringify(item)) + "</script>");
  });

  lines.push("  " + SEO_END_LINE);
  return lines.join("\n");
}

function replaceRegion(html, metaBlock) {
  var start = html.indexOf(START_LINE);
  var end = html.indexOf(END_LINE);
  if (start === -1 || end === -1 || end < start) return null;
  end += END_LINE.length;
  return html.slice(0, start) + metaBlock + html.slice(end);
}

function replaceSeoRegion(html, schemaBlock) {
  var start = html.indexOf(SEO_START_LINE);
  var end = html.indexOf(SEO_END_LINE);
  if (start === -1 || end === -1 || end < start) return null;
  end += SEO_END_LINE.length;
  return html.slice(0, start) + schemaBlock + html.slice(end);
}

var M = loadConfig();
var pages = M.PAGE_META || {};
var written = 0;

Object.keys(pages).forEach(function (urlPath) {
  var page = pages[urlPath];
  var file = page.file;
  if (!file) {
    console.log("SKIP (no file): " + urlPath);
    return;
  }

  var full = path.join(ROOT, file);
  if (!fs.existsSync(full)) {
    console.log("SKIP (no page): " + file);
    return;
  }

  var html = fs.readFileSync(full, "utf8");
  var updated = replaceRegion(html, buildMeta(urlPath, page));

  if (updated === null) {
    console.log("SKIP (no markers): " + file);
    return;
  }

  var withSchema = replaceSeoRegion(updated, buildSchemaBlock(M, urlPath));
  if (withSchema !== null) updated = withSchema;

  if (updated !== html) {
    fs.writeFileSync(full, updated, "utf8");
    console.log("Updated " + file);
  } else {
    console.log("Unchanged " + file);
  }

  written++;
});

console.log("Done. " + written + " static page(s) processed.");
