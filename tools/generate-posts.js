/* =========================================================================
   MicFi - tools/generate-posts.js
   Writes the social share metadata (Open Graph + Twitter) into each post's
   static page, using the post list in js/blog.js as the single source.

   Why this exists: link previews on WhatsApp, Facebook, X, LinkedIn,
   Telegram, Slack, Discord and others are built by crawlers that do NOT run
   JavaScript. They only read the raw HTML, so the correct tags must be
   written into blog/<slug>/index.html at build time.

   Each post uses its own banner (post.image). Posts with no image fall back
   to assets/blog/default.png.

   Run it after adding or editing a post:
       node tools/generate-posts.js
   No need to edit this file.
   ========================================================================= */
"use strict";

var fs = require("fs");
var path = require("path");
var vm = require("vm");

var ROOT = path.resolve(__dirname, "..");
var SITE = "https://micfi.net";
var FALLBACK_IMAGE = "/assets/blog/default.png";
var START_LINE = "<!-- META:START";
var END_LINE = "<!-- META:END -->";

function loadSite() {
  var sandbox = {};
  sandbox.window = sandbox;
  sandbox.MicFi = {};
  vm.createContext(sandbox);

  ["js/config.js", "js/blog.js"].forEach(function (file) {
    var code = fs.readFileSync(path.join(ROOT, file), "utf8");
    vm.runInContext(code, sandbox, { filename: file });
  });

  return sandbox.MicFi;
}

function esc(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function stripHtml(value) {
  return String(value).replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim();
}

function imagePath(post) {
  return post.image && String(post.image).trim() ? String(post.image).trim() : FALLBACK_IMAGE;
}

/* The picture people see when the post is shared. It is the link preview
   card drawn by tools/generate-og.js, one card per post. The post's own
   banner still shows at the top of the page. */
function shareImagePath(post) {
  return "/assets/og/post-" + post.slug + ".png";
}

function imageDims(relPath) {
  var file = path.join(ROOT, relPath.replace(/^\//, ""));
  if (!fs.existsSync(file)) return null;
  var b = fs.readFileSync(file);
  if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4E && b[3] === 0x47) {
    return { type: "image/png", w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
  }
  if (b[0] === 0xFF && b[1] === 0xD8) {
    var i = 2;
    while (i < b.length - 1) {
      if (b[i] !== 0xFF) { i++; continue; }
      var mark = b[i + 1];
      if (mark >= 0xC0 && mark <= 0xCF && mark !== 0xC4 && mark !== 0xC8 && mark !== 0xCC) {
        return { type: "image/jpeg", h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) };
      }
      if (mark === 0xD8 || mark === 0xD9 || (mark >= 0xD0 && mark <= 0xD7)) { i += 2; continue; }
      i += 2 + b.readUInt16BE(i + 2);
    }
  }
  return null;
}

function jsonLd(obj) {
  return JSON.stringify(obj)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/&/g, "\\u0026");
}

function buildStructuredData(post, M) {
  var url = SITE + "/blog/" + post.slug + "/";
  var image = SITE + shareImagePath(post);
  var desc = post.excerpt || stripHtml(post.body);
  var name = M.BRAND_NAME || "MicFi";

  var article = {
    "@context": "https://schema.org",
    "@type": "BlogPosting",
    mainEntityOfPage: { "@type": "WebPage", "@id": url },
    headline: post.title,
    description: desc,
    image: [image],
    datePublished: post.date,
    author: { "@type": "Organization", name: name, url: SITE + "/" },
    publisher: {
      "@type": "Organization",
      name: name,
      alternateName: M.BRAND_ALTERNATE || [],
      url: SITE + "/",
      logo: { "@type": "ImageObject", url: SITE + "/assets/mark.png" }
    }
  };
  if (post.tag) article.keywords = post.tag;

  var breadcrumb = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "Home", item: SITE + "/" },
      { "@type": "ListItem", position: 2, name: "Blog", item: SITE + "/blog/" },
      { "@type": "ListItem", position: 3, name: post.title, item: url }
    ]
  };

  return (
    '  <script type="application/ld+json">' + jsonLd(article) + "</script>\n" +
    '  <script type="application/ld+json">' + jsonLd(breadcrumb) + "</script>"
  );
}

function buildMeta(post, M) {
  var url = SITE + "/blog/" + post.slug + "/";
  var rel = shareImagePath(post);
  var image = SITE + rel;
  var desc = post.excerpt || stripHtml(post.body);
  var dims = imageDims(rel);
  var name = M.BRAND_NAME || "MicFi";

  var lines = [
    START_LINE + " generated by tools/generate-posts.js from js/blog.js. Do not edit by hand. -->",
    "  <title>" + esc(post.title) + " - " + esc(name) + "</title>",
    '  <meta name="description" content="' + esc(desc) + '">',
    '  <link rel="canonical" href="' + esc(url) + '">',
    '  <meta property="og:type" content="article">',
    '  <meta property="og:site_name" content="' + esc(name) + '">',
    '  <meta property="og:title" content="' + esc(post.title) + '">',
    '  <meta property="og:description" content="' + esc(desc) + '">',
    '  <meta property="og:url" content="' + esc(url) + '">',
    '  <meta property="og:image" content="' + esc(image) + '">'
  ];

  if (dims) {
    lines.push('  <meta property="og:image:type" content="' + dims.type + '">');
    lines.push('  <meta property="og:image:width" content="' + dims.w + '">');
    lines.push('  <meta property="og:image:height" content="' + dims.h + '">');
  }

  lines.push(
    '  <meta property="og:image:alt" content="' + esc(post.title) + '">',
    '  <meta property="og:locale" content="en_US">',
    '  <meta property="article:published_time" content="' + esc(post.date) + '">'
  );

  if (post.tag) lines.push('  <meta property="article:tag" content="' + esc(post.tag) + '">');

  lines.push(
    '  <meta name="twitter:card" content="summary_large_image">',
    '  <meta name="twitter:title" content="' + esc(post.title) + '">',
    '  <meta name="twitter:description" content="' + esc(desc) + '">',
    '  <meta name="twitter:image" content="' + esc(image) + '">',
    '  <meta name="twitter:image:alt" content="' + esc(post.title) + '">'
  );

  lines.push(buildStructuredData(post, M));
  lines.push("  " + END_LINE);

  return lines.join("\n");
}

function replaceRegion(html, metaBlock) {
  var start = html.indexOf(START_LINE);
  var end = html.indexOf(END_LINE);
  if (start === -1 || end === -1 || end < start) return null;
  end += END_LINE.length;
  return html.slice(0, start) + metaBlock + html.slice(end);
}

var M = loadSite();
var posts = M.BLOG || [];
var written = 0;

posts.forEach(function (post) {
  var file = path.join(ROOT, "blog", post.slug, "index.html");
  if (!fs.existsSync(file)) {
    console.log("SKIP (no page): blog/" + post.slug + "/index.html");
    return;
  }

  var html = fs.readFileSync(file, "utf8");
  var updated = replaceRegion(html, buildMeta(post, M));

  if (updated === null) {
    console.log("SKIP (no markers): blog/" + post.slug + "/index.html");
    return;
  }

  if (updated !== html) {
    fs.writeFileSync(file, updated, "utf8");
    console.log("Updated blog/" + post.slug + "/index.html");
  } else {
    console.log("Unchanged blog/" + post.slug + "/index.html");
  }

  var dims = imageDims(imagePath(post));
  if (dims && dims.h) {
    var ratio = dims.w / dims.h;
    if (ratio < 1.7 || ratio > 2.1) {
      console.log("  note: " + imagePath(post) + " is " + dims.w + "x" + dims.h +
        " (ratio " + Math.round(ratio * 100) / 100 + "). Close to 1.91 (e.g. 1200x630) looks best on social cards.");
    }
  } else if (!dims) {
    console.log("  note: could not read image size for " + imagePath(post) + ".");
  }

  written++;
});

console.log("Done. " + written + " post page(s) processed from " + posts.length + " post(s).");
