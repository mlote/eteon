/* =========================================================================
   MicFi - tools/generate-content.js
   Writes the visible page content into the static HTML, so search engines,
   social crawlers and any visitor without JavaScript can read the real
   content of every page.

   Why this exists: the site builds its lists (blog posts, projects,
   services, home teasers) with JavaScript. Crawlers that do not run
   JavaScript would see empty pages, and crawlers that do run it have to
   render before they can index the content. Pre-rendering the same markup
   into the HTML fixes both.

   The markup is produced by the very same template functions the site
   uses at runtime (M.postCard, M.projectCard, M.serviceBlock, ...), so
   the static HTML and the client-rendered HTML are identical.

   Run it after adding a post, project, service or FAQ item:
       node tools/generate-content.js
   No need to edit this file.
   ========================================================================= */
"use strict";

var fs = require("fs");
var path = require("path");
var vm = require("vm");

var ROOT = path.resolve(__dirname, "..");

function loadSite() {
  var sandbox = {};
  sandbox.window = sandbox;
  sandbox.MicFi = {};
  sandbox.document = {
    querySelector: function () { return null; },
    querySelectorAll: function () { return []; },
    addEventListener: function () {}
  };
  sandbox.navigator = { share: null, clipboard: null };
  vm.createContext(sandbox);

  ["js/config.js", "js/icons.js", "js/blog.js", "js/projects.js", "js/services.js"].forEach(function (file) {
    var code = fs.readFileSync(path.join(ROOT, file), "utf8");
    vm.runInContext(code, sandbox, { filename: file });
  });

  return sandbox.MicFi;
}

function esc(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function sortedPosts(posts) {
  var copy = posts.slice();
  copy.sort(function (a, b) {
    return String(b.date).localeCompare(String(a.date));
  });
  return copy;
}

function writeRegion(file, name, html, indent) {
  var startMark = "<!-- CONTENT:" + name + " START generated by tools/generate-content.js. Do not edit by hand. -->";
  var endMark = "<!-- CONTENT:" + name + " END -->";

  var pad = indent || "";
  var body = html
    .replace(/\n+$/, "")
    .split("\n")
    .map(function (line) { return line ? pad + line : line; })
    .join("\n");

  var block = startMark + "\n" + body + "\n" + endMark;

  var full = path.join(ROOT, file);
  if (!fs.existsSync(full)) {
    console.log("SKIP (no file): " + file);
    return false;
  }

  var source = fs.readFileSync(full, "utf8");
  var start = source.indexOf(startMark);
  var end = source.indexOf(endMark);

  if (start === -1 || end === -1 || end < start) {
    console.log("SKIP (no markers): " + file + " [" + name + "]");
    return false;
  }

  var updated = source.slice(0, start) + block + source.slice(end + endMark.length);
  if (updated !== source) {
    fs.writeFileSync(full, updated, "utf8");
    console.log("Updated " + file + " [" + name + "]");
  } else {
    console.log("Unchanged " + file + " [" + name + "]");
  }
  return true;
}

function fillElement(file, attrPattern, html) {
  var full = path.join(ROOT, file);
  if (!fs.existsSync(full)) {
    console.log("SKIP (no file): " + file);
    return false;
  }

  var source = fs.readFileSync(full, "utf8");
  var re = new RegExp("(<(\\w+)[^>]*" + attrPattern + "[^>]*>)([\\s\\S]*?)(</\\2>)", "g");
  var updated = source.replace(re, function (match, open, tag, inner, close) {
    return open + html + close;
  });

  if (updated !== source) {
    fs.writeFileSync(full, updated, "utf8");
    console.log("Updated " + file + " [" + attrPattern + "]");
  } else {
    console.log("Unchanged " + file + " [" + attrPattern + "]");
  }
  return true;
}

var M = loadSite();
var posts = sortedPosts(M.BLOG || []);
var projects = M.PROJECTS || [];
var services = M.SERVICES || [];

/* ---------- Blog post pages: title, date, tag, hero, body ---------- */
posts.forEach(function (post) {
  var file = path.join("blog", post.slug, "index.html");
  var title = M.blogDate(post.date);
  var tag = post.tag
    ? '<span class="tag" data-post-tag>' + esc(post.tag) + "</span>"
    : '<span class="tag" data-post-tag hidden></span>';

  var html =
    '<div class="page-intro">\n' +
    '  <h1 class="page-title" data-post-title>' + esc(post.title) + "</h1>\n" +
    "</div>\n" +
    '<div class="post-meta">\n' +
    "  " + tag + "\n" +
    '  <span data-post-date>' + esc(title) + "</span>\n" +
    "  <span>MicFi</span>\n" +
    "</div>\n" +
    '<div class="post-hero" data-post-hero>' + M.postHero(post) + "</div>\n" +
    '<div class="prose" data-post-body>' + (post.body || "") + "</div>";

  writeRegion(file, "post", html, "      ");
});

/* ---------- Blog list page: post cards ---------- */
if (posts.length) {
  var listHtml = "";
  for (var i = 0; i < posts.length; i++) listHtml += M.postCard(posts[i]) + "\n";
  writeRegion(path.join("blog", "index.html"), "blog-list", listHtml, "        ");
}

/* ---------- Home page: blog teaser + projects teaser ---------- */
if (posts.length) {
  var teaserHtml = "";
  for (var t = 0; t < Math.min(3, posts.length); t++) teaserHtml += M.postCard(posts[t]) + "\n";
  writeRegion("index.html", "blog-teaser", teaserHtml, "        ");
}

if (projects.length) {
  var projHtml = "";
  for (var p = 0; p < Math.min(3, projects.length); p++) projHtml += M.projectCard(projects[p]) + "\n";
  writeRegion("index.html", "projects-teaser", projHtml, "        ");
}

/* ---------- Projects page: project cards ---------- */
if (projects.length) {
  var gridHtml = "";
  for (var g = 0; g < projects.length; g++) gridHtml += M.projectCard(projects[g]) + "\n";
  writeRegion(path.join("projects", "index.html"), "projects-grid", gridHtml, "        ");
}

/* ---------- About page: FAQ ---------- */
if (M.FAQ && M.FAQ.length) {
  var faqHtml = "";
  for (var f = 0; f < M.FAQ.length; f++) {
    faqHtml +=
      '<article class="card faq-item">\n' +
      '  <h3 class="row-title">' + esc(M.FAQ[f].q) + "</h3>\n" +
      '  <p class="row-text">' + esc(M.FAQ[f].a) + "</p>\n" +
      "</article>\n";
  }
  writeRegion(path.join("about", "index.html"), "faq", faqHtml, "        ");
}

/* ---------- Services page: service blocks ---------- */
if (services.length) {
  var svcHtml = "";
  for (var s = 0; s < services.length; s++) svcHtml += M.serviceBlock(services[s]) + "\n";
  writeRegion(path.join("services", "index.html"), "services-list", svcHtml, "        ");
}

/* ---------- Home page: short service rows ---------- */
if (services.length) {
  var homeSvcHtml = "";
  for (var hs = 0; hs < services.length; hs++) homeSvcHtml += M.homeServiceRow(services[hs]) + "\n";
  writeRegion("index.html", "home-services", homeSvcHtml, "        ");
}

/* ---------- Projects page: the line under the title ---------- */
if (projects.length) {
  fillElement(path.join("projects", "index.html"), "data-projects-sub", esc(M.projectsSubText()));
}

/* ---------- Projects page: the call to action under the grid ---------- */
if (projects.length && M.PROJECTS_PAGE) {
  var ctaHtml =
    '<p class="cta-text">' + esc(M.PROJECTS_PAGE.cta) + "</p>\n" +
    '<a class="btn btn-primary" href="/contact/">' + esc(M.PROJECTS_PAGE.ctaButton) + "</a>";
  writeRegion(path.join("projects", "index.html"), "projects-cta", ctaHtml, "      ");
}

console.log(
  "Done. " + posts.length + " post(s), " + projects.length + " project(s), " +
  services.length + " service(s) processed."
);
